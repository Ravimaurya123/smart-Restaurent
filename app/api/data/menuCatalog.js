function getSamplePrice(category, foodType, name, index) {
  const base = categoryBasePrices[category] || 99;
  const nonVegExtra = foodType === "Non-Veg" ? 30 : 0;
  const premiumWords = /supreme|maharaja|special|double|cheese burst|prawn|rogan|afghani|seafood/i;
  const premiumExtra = premiumWords.test(name) ? 50 : 0;

  return Math.round((base + nonVegExtra + premiumExtra + (index % 4) * 10) / 5) * 5;
}

export const foodCatalog = menuCatalog.flatMap((group) => {
  const items = [];

  for (const [foodType, list] of [
    ["Veg", group.veg],
    ["Non-Veg", group.nonVeg],
  ]) {
    if (!list) continue;

    list.split("|").forEach((rawName, index) => {
      const name = rawName.trim();

      items.push({
        catalogId: `${group.category}-${name}`
          .toLowerCase()
          .replace(/[^a-z0-9]+/g, "-"),
        name,
        category: group.category,
        foodType,
        price: getSamplePrice(
          group.category,
          foodType,
          name,
          index
        ),
        description: `${name} – freshly prepared with quality ingredients.`,
        image: group.image,
        stock: 50,
        rating: 4.2 + (index % 7) / 10,
        isAvailable: true,
      });
    });
  }

  return items;
});